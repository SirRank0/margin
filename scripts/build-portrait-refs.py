#!/usr/bin/env python3
"""Build the small portrait grids the screenshot reader compares against.

Two kinds of art per hero:
- icon: the cut-out head used on the post-match scoreboard (public/heroes/<id>.webp).
- card: the hero card art the in-game top bar and the pause-screen list show.
- bar: the tall top-bar art, a second look at the in-game top bar.
- mini: the small map head, a second look at the scoreboard.

Each picture is squeezed onto a coarse grid and a fine grid of RGBA cells (alpha-weighted box average)
and written to src/data/portrait-refs.ts. Run by hand when heroes or art change. Needs Pillow.
"""

from __future__ import annotations

import base64
import io
import re
import urllib.request
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/data/portrait-refs.ts"
GRIDS = {"icon": {"fine": (16, 16), "coarse": (8, 8)}, "card": {"fine": (14, 19), "coarse": (7, 10)}, "bar": {"fine": (12, 20), "coarse": (6, 10)}, "mini": {"fine": (16, 16), "coarse": (8, 8)}}


def hero_ids() -> list[int]:
    text = (ROOT / "src/lib/deadlock/heroes.ts").read_text()
    return [int(m) for m in re.findall(r"\{ id: (\d+), name:", text)]


def card_urls() -> dict[int, str]:
    text = (ROOT / "src/data/hero-portraits.ts").read_text()
    return {int(i): url for i, url in re.findall(r"^\s*(\d+): \{ icon: \"[^\"]*\", card: \"([^\"]*)\"", text, re.M)}


def fetch(url: str) -> Image.Image:
    req = urllib.request.Request(url, headers={"User-Agent": "margin-portrait-refs"})
    with urllib.request.urlopen(req, timeout=30) as res:
        return Image.open(io.BytesIO(res.read())).convert("RGBA")


def painted_square(im: Image.Image) -> tuple[float, float, float, float]:
    box = im.getchannel("A").point(lambda a: 255 if a > 16 else 0).getbbox()
    if not box:
        return (0, 0, im.width, im.height)
    x0, y0, x1, y1 = box
    side = max(x1 - x0, y1 - y0)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    return (cx - side / 2, cy - side / 2, cx + side / 2, cy + side / 2)


def grid(im: Image.Image, box: tuple[float, float, float, float], size: tuple[int, int]) -> str:
    # Pad so a square that runs past the edge still averages in transparent pixels.
    pad = 64
    canvas = Image.new("RGBA", (im.width + pad * 2, im.height + pad * 2), (0, 0, 0, 0))
    canvas.paste(im, (pad, pad))
    shifted = (box[0] + pad, box[1] + pad, box[2] + pad, box[3] + pad)
    small = canvas.convert("RGBa").resize(size, Image.Resampling.BOX, box=shifted).convert("RGBA")
    return base64.b64encode(small.tobytes()).decode("ascii")


def main() -> None:
    urls = card_urls()
    rows: list[str] = []
    for hero in hero_ids():
        icon_path = ROOT / f"public/heroes/{hero}.webp"
        parts: list[str] = []
        if icon_path.exists():
            icon = Image.open(icon_path).convert("RGBA")
            box = painted_square(icon)
            parts.append(f'icon: ["{grid(icon, box, GRIDS["icon"]["coarse"])}", "{grid(icon, box, GRIDS["icon"]["fine"])}"]')
        url = urls.get(hero)
        if url and url.endswith("_card.webp"):
            card = fetch(url)
            if card.height > card.width:
                box = (0, 0, card.width, card.width * 380 / 280)
                parts.append(f'card: ["{grid(card, box, GRIDS["card"]["coarse"])}", "{grid(card, box, GRIDS["card"]["fine"])}"]')
            tall = fetch(url.replace("_card.webp", "_vertical.webp"))
            if tall.height > tall.width:
                box = (0, 0, tall.width, tall.width * 5 / 3)
                parts.append(f'bar: ["{grid(tall, box, GRIDS["bar"]["coarse"])}", "{grid(tall, box, GRIDS["bar"]["fine"])}"]')
            mini = fetch(url.replace("_card.webp", "_mm.webp"))
            box = painted_square(mini)
            parts.append(f'mini: ["{grid(mini, box, GRIDS["mini"]["coarse"])}", "{grid(mini, box, GRIDS["mini"]["fine"])}"]')
        rows.append(f"  {hero}: {{ {', '.join(parts)} }},")
        print(hero, len(parts))
    grids = ", ".join(f'{kind}: {{ coarse: [{g["coarse"][0]}, {g["coarse"][1]}], fine: [{g["fine"][0]}, {g["fine"][1]}] }}' for kind, g in GRIDS.items())
    OUT.write_text(
        "/** Generated by scripts/build-portrait-refs.py. Hero art squeezed onto small RGBA grids, base64. Do not edit. */\n"

        f"export const PORTRAIT_GRIDS = {{ {grids} }} as const;\n\n"
        "/** [coarse, fine] per art style. `icon` is the scoreboard head, `card` the top-bar and pause-list art, `bar` the tall top-bar art, `mini` the small map head. */\n"
        "export const PORTRAIT_REFS: Record<number, { icon?: [string, string]; card?: [string, string]; bar?: [string, string]; mini?: [string, string] }> = {\n"
        + "\n".join(rows)
        + "\n};\n"
    )


if __name__ == "__main__":
    main()
